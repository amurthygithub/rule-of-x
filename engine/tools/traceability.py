"""Generate engine/TRACEABILITY.md (spec 19.1): every formula in formulas.py with the paper label it implements,
the spec section, the notes section and its status, and every parameter with its grounding class, source and the
outputs it affects.

Run from engine/:   python tools/traceability.py
tests/test_traceability.py fails when the file is out of date."""
from __future__ import annotations

import inspect
import re
import sys
from pathlib import Path

ENGINE = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ENGINE / "src"))

TAG = re.compile(r"Implements:\s*(?P<impl>.*?)\s*\|\s*Spec:\s*(?P<spec>.*?)\s*\|\s*Notes:\s*(?P<notes>.*?)\s*\|\s*Status:\s*(?P<status>\S+)", re.S)


def formula_rows():
    from autofrontier import formulas as F
    rows = []
    for name, fn in inspect.getmembers(F, inspect.isfunction):
        if name.startswith("_") or fn.__module__ != F.__name__:
            continue
        doc = inspect.getdoc(fn) or ""
        m = TAG.search(doc)
        line = inspect.getsourcelines(fn)[1]
        rows.append({"name": name, "line": line, "implements": m and " ".join(m["impl"].split()), "spec": m and " ".join(m["spec"].split()),
                     "notes": m and " ".join(m["notes"].split()), "status": m and m["status"],
                     "summary": " ".join(doc.split("\n\n")[0].split())[:160]})
    return sorted(rows, key=lambda r: r["line"])


def render() -> str:
    from autofrontier import __version__
    from autofrontier.config import load_params
    from autofrontier.report import AFFECTS as SECTION_OUTPUTS
    rows = formula_rows()
    p = load_params()
    L = ["# Traceability", "",
         f"Generated by tools/traceability.py for autofrontier {__version__}. Do not edit by hand; run the tool after changing "
         "formulas.py or defaults.yaml. tests/test_traceability.py fails when this file is out of date.", "",
         "## Formulas", "",
         "Status: theory (a result of the Part II theory notes, cross-tested against code/verify_part2_*.py where a reference "
         "exists), spec (specified in notes/unified_model_spec.md without a theory proof), provisional (an engine rule awaiting "
         "theory), superseded (kept for comparison).", "",
         "| function | line | implements | spec | notes | status |", "|---|---|---|---|---|---|"]
    for r in rows:
        L.append(f"| `{r['name']}` | {r['line']} | {r['implements'] or ''} | {r['spec'] or ''} | {r['notes'] or ''} | {r['status'] or 'MISSING'} |")
    counts = {}
    for r in rows:
        counts[r["status"]] = counts.get(r["status"], 0) + 1
    L += ["", "Counts by status: " + ", ".join(f"{k} {v}" for k, v in sorted(counts.items(), key=lambda kv: str(kv[0]))) + ".", ""]
    L += ["## Parameters", "",
          "Grounding classes (spec 21.1): a sourced, b precedent, c calibrated or derived, d scenario (no measurement; reported "
          "over its range), setting, policy. Class d values never appear as point results.", "",
          "| key | value | range | class | source or basis | outputs affected |", "|---|---|---|---|---|---|"]
    for row in p.table():
        sec = row["key"].split(".")[0]
        src = str(row.get("source") or row.get("basis") or "").replace("|", "/").replace("\n", " ")
        src = src[:140] + ("..." if len(src) > 140 else "")
        val = str(row["value"]).replace("|", "/")[:40]
        rng = str(row["range"]).replace("|", "/")[:40]
        L.append(f"| `{row['key']}` | {val} | {rng} | {row['grounding']} | {src} | {SECTION_OUTPUTS.get(sec, '')} |")
    gc = {}
    for row in p.table():
        gc[row["grounding"]] = gc.get(row["grounding"], 0) + 1
    L += ["", "Counts by class: " + ", ".join(f"{k} {v}" for k, v in sorted(gc.items(), key=lambda kv: str(kv[0]))) + ".", ""]
    return "\n".join(L)


def main():
    out = ENGINE / "TRACEABILITY.md"
    out.write_text(render(), encoding="utf-8")
    print(f"wrote {out}")


if __name__ == "__main__":
    main()
