#!/usr/bin/env python3
"""
make_labor_macros.py: writes part2/tables/labor_macros.tex, the numbers of the talent example in
part2/theory_labor.tex (prop:labor-talent) that come from the running invoice example.

Reads   data/examples/invoice_chain.json (generated by code/examples/invoice_chain.py).
Writes  part2/tables/labor_macros.tex. Do not edit the output by hand; rerun this script whenever the JSON changes.
Check   code/verify_part2_labor.py (L3a, L3b, L3f) recomputes every value from the JSON independently and fails if
        the macro file is stale.

Run:  python3 code/make_labor_macros.py
"""
import json
import os

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
JSON_PATH = os.path.join(ROOT, "data", "examples", "invoice_chain.json")
OUT_PATH = os.path.join(ROOT, "part2", "tables", "labor_macros.tex")

# Inputs of the hire-or-contract example that are not in the invoice chain (scenario values stated in the text).
CONTRACT = dict(dG=5.0, u_ct=0.5, c_hire_weeks=13.5, delta_rp=0.15, T_rp=2.0, T_lead=0.25, T_ct=1.0 / 12.0, W_hat=2.0e6)


def usd(x, step=1):
    """Dollar amount rounded to `step`, with LaTeX thousands separators."""
    v = int(round(x / step) * step)
    return "\\$" + f"{v:,}".replace(",", "{,}")


def compute(ic):
    """Labor-example numbers from the invoice JSON. Returns {macro name: LaTeX string}."""
    t, i = ic["transition"], ic["inputs"]
    prem = i["ai_engineer_premium"]["value"] - 1.0          # p: the engine stores 1 + p
    tau = i["tau_L"]["value"]                                 # payroll loading on an annual wage
    w_se = i["ai_engineer_wage"]["value"]                     # w^SE, software-developer base wage
    w_ai = w_se * (1 + prem) * (1 + tau)                      # w^AI, prop:labor-talent and ass:labor-talent
    F, F_build = t["F"], t["F_build"]
    prem_part = F_build * prem / (1 + prem)                   # premium inside the build (F_build is priced at w^AI)
    F0 = F - prem_part                                        # investment at the developer wage
    l_ai = (F_build / (1 + prem)) / F0                        # engineering share of F0
    c = CONTRACT
    thr = (c["delta_rp"] * c["T_rp"] + c["c_hire_weeks"] / 52.0
           + c["W_hat"] * (c["T_lead"] - c["T_ct"]) / (c["dG"] * w_ai)) / c["u_ct"]   # prop:labor-talent(d)
    return {
        "labPremRate": f"{100 * prem:.0f}\\%",
        "labTauL": f"{tau:.2f}",
        "labWSE": usd(w_se),
        "labWAI": usd(w_ai),
        "labPremAmt": usd(prem_part, 100),
        "labPremShareF": f"{100 * prem_part / F:.1f}\\%",
        "labLAI": f"{l_ai:.2f}",
        "labLAIp": f"{100 * l_ai * prem:.1f}\\%",
        "labContractT": f"{thr:.2f}",
    }


def main():
    with open(JSON_PATH) as fh:
        ic = json.load(fh)
    macros = compute(ic)
    lines = ["% Generated by code/make_labor_macros.py from data/examples/invoice_chain.json "
             f"(version {ic['meta']['version']}); do not edit.",
             "% Numbers of the talent example in part2/theory_labor.tex that come from the running invoice example;",
             "% checked against the JSON by code/verify_part2_labor.py (L3a, L3b, L3f)."]
    lines += [f"\\newcommand{{\\{k}}}{{{v}}}" for k, v in macros.items()]
    with open(OUT_PATH, "w") as fh:
        fh.write("\n".join(lines) + "\n")
    print(f"wrote {os.path.relpath(OUT_PATH, ROOT)}: " + ", ".join(f"{k}={v}" for k, v in macros.items()))


if __name__ == "__main__":
    main()
