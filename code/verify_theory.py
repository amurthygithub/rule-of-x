def simulate_program(Nn, ncap, nwaves, varpi, pdis, plan='greedy', revert_low=False, rng=None, bdist=None):
    """Identical processes; returns list of embedded b's after nwaves waves (all waves embedded by t).
    Each attempt embeds with prob varpi*(1-pdis); plan 'greedy' fills each wave with available processes,
    'random' attempts a random number up to ncap; revert_low reverts embedded processes with b < 0.5 (allowed)."""
    status = np.zeros(Nn)          # 0 available, 1 embedded
    bvals = np.zeros(Nn)
    attempts = 0
    for w in range(nwaves):
        avail = np.where(status == 0)[0]
        k_ = len(avail) if plan == 'greedy' else rng.integers(0, len(avail) + 1)
        k_ = min(k_, ncap)
        chosen = rng.choice(avail, size=k_, replace=False) if k_ > 0 else []
        for i in chosen:
            attempts += 1
            if rng.random() < varpi and rng.random() >= pdis:
                status[i] = 1
                bvals[i] = bdist(rng)
        if revert_low:
            low = np.where((status == 1) & (bvals < 0.5))[0]
            status[low] = 0
    return bvals[status == 1], attempts


