# Decision D-2: model-facing slope is the Psi_chi slope, a least-squares slope of the chi-quantile frontier on an equally
# spaced grid of growth. Under a common frontier with k = 0 and the window read as excess growth Delta in [0, W]:
# LS slope of m0 - (Delta/ell)^beta on the grid is -S_beta/ell^beta, so ell = (S_beta/b)^alpha for an estimated slope -b,
# with S_beta the LS slope of Delta^beta on the grid (~ 6 beta W^(beta-1)/((beta+1)(beta+2)) for a dense grid); the
# frontier's steepest slope in the window is then beta W^(beta-1)/ell^beta ~ (beta+1)(beta+2) b/6.


def ls_slope(xv, yv):
    xv, yv = np.asarray(xv, float), np.asarray(yv, float)
    return float(np.sum((xv - xv.mean()) * (yv - yv.mean())) / np.sum((xv - xv.mean()) ** 2))


def ell_from_slope(b, a_, W=0.6, J=12):
    grid = np.linspace(0, W, J + 1)
    Sb = ls_slope(grid, grid ** (1 / a_))
    return (Sb / b) ** a_, Sb


