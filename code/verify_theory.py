def single_wave_ok(mask, use, cap):
    idx = [i for i in range(use.shape[0]) if mask >> i & 1]
    return all(use[idx, r].sum() <= cap[r] + 1e-12 for r in range(use.shape[1]))


def min_waves(Nn, use, cap):
    """mw[Z] = least number of capacity-feasible waves that partition Z (inf if some process fits no wave)."""
    full = 1 << Nn
    feas = [single_wave_ok(m, use, cap) for m in range(full)]
    mw = [math.inf] * full
    mw[0] = 0
    for Z in range(1, full):
        low = Z & -Z
        S_ = Z
        best = math.inf
        while S_:
            if (S_ & low) and feas[S_]:
                best = min(best, 1 + mw[Z ^ S_])
            S_ = (S_ - 1) & Z
        mw[Z] = best
    return mw


def theta_Z(Z, th0, dth):
    th = th0.copy()
    for i in range(dth.shape[0]):
        if Z >> i & 1:
            th = th + dth[i]
    return th


def Rstar_theta(th, X_, a_, hh):
    m0_, k_, lnlam, G_ = th
    return closed_form(m0_, G_, k_, X_, math.exp(lnlam) * hh, a_)[2]


def n_waves(t, Temb, T):
    return 0 if t < Temb else math.floor((t - Temb) / T + 1e-12) + 1


