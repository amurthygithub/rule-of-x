def log_equal(a, b):
    """For positive expressions a, b: check log(a) - log(b) == 0 after forced log expansion."""
    d = sp.expand_log(sp.log(a), force=True) - sp.expand_log(sp.log(b), force=True)
    return sp.simplify(d) == 0


def is_zero(e):
    return sp.simplify(e) == 0


