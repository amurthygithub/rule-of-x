# 28n uniform clock with calendar-time disruption: p_emb = varpi exp(-nu_D (1 + nu_R T_frz) T_emb)
def sim_uniform(Nn, ncap, varpi, nuD, Temb, Tpar, clock, t_cal, rng):
    """Greedy plan; waves and lags in program time; disruption Poisson in calendar time."""
    status = np.zeros(Nn, dtype=int)           # 0 available, 1 working in flight, 2 embedded
    emb_time = np.full(Nn, np.inf)
    nW = int((t_cal / clock) / Tpar) + 2
    for w in range(nW):
        start = w * Tpar
        # embed processes whose flight ended
