def half_up(x, nd=0):
    q = 10 ** nd
    return math.floor(x * q + 0.5) / q


def mnum(name):
    """Numeric value printed by a generated macro, or None."""
    if name not in TEXM:
        return None
    s_ = TEXM[name].replace('$-$', '-').replace('{,}', '').strip()
    try:
        return float(s_)
    except ValueError:
        return None


def printed(name, x, nd=0, pct=True):
    """[text] check helper: the macro prints x as code/paper1_macros.py would (half-up rounding)."""
    v = mnum(name)
    return v is not None and abs(v - half_up(100 * x if pct else x, nd)) < 1e-9


def tex_table_rows(label, path=('sections', 'appendix_proofs.tex')):
    """Rows of the tabular after \\label{label}: first cell -> remaining cells (strings)."""
    src = open(_osh.path.join(_ROOT, *path)).read()
    a0 = src.index('\\label{' + label + '}')
    b0 = src.index('\\end{tabular}', a0)
    rows = {}
    for line in src[a0:b0].split('\n'):
        if line.lstrip().startswith('%'):
            continue
        cells = [c.strip() for c in line.strip().rstrip('\\').split('&')]
        if len(cells) >= 4:
            rows[cells[0]] = cells[1:]
    return rows


