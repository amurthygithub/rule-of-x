def simulate_policy(lam_, a_, sbar_, s0, m0_, G_, k_, X_, durations, sigmas, n_sub=4000):
    """Exact logistic share path under piecewise-constant sigma (frontier margins); returns integrals."""
    y_ = X_ - k_
    u0 = s0 / sbar_
    logit = math.log(u0 / (1 - u0))
    I_pos, I_yDelta, I_Delta = 0.0, 0.0, 0.0
    for tau, sg in zip(durations, sigmas):
        nu_ = lam_ * sg**a_
        t = np.linspace(0, tau, n_sub + 1)
        h_t = 1 / (1 + np.exp(logit + nu_ * t))  # h = 1 - u
        Delta_t = nu_ * h_t
