def closed_form(m0_, G_, k_, X_, ell, a_):
    y_ = X_ - k_
    if y_ <= 0:
        return 0.0, 0.0, m0_ + y_ * G_
    D_ = ell ** (1 / (1 - a_)) * (a_ * y_) ** (a_ / (1 - a_))
    sg = a_ * y_ * D_
    return D_, sg, m0_ + y_ * G_ + (1 - a_) * y_ * D_


