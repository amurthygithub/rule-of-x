def firm_choice(m0_, k_, ell, X_, a_, G_, sbar_cap=np.inf):
    """Rule-of-X choice of a firm with a financing cap; returns (g, m, R)."""
    y_ = X_ - k_
    if y_ <= 0:
        return G_, m0_ - k_ * G_, m0_ + y_ * G_
    sg = min((a_ * ell * y_) ** (1 / (1 - a_)), sbar_cap)
    g_ = G_ + ell * sg**a_
    m_ = m0_ - k_ * g_ - sg
    return g_, m_, X_ * g_ + m_


